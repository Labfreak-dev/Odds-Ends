/* Gravemark — tools/grok-parts.js
   Generates GROK-PARTS.md: the brief for painting characters as separate body
   parts, which is what the skeletal animator wears.

   This is the ask that replaces "animate this". An image generator cannot
   animate, but it CAN paint one part of a figure at a time from a reference
   painting — and once the parts exist, one rig and one set of keyframes move
   every character in the game the way Path of Idle moves.

       node tools/grok-parts.js > GROK-PARTS.md
*/
"use strict";
const fs = require("fs");
const path = require("path");
const { load } = require("./harness");

const GM = load({ quiet: true });
GM.startSeason("s_none");

const ART = path.join(__dirname, "..", "art");
const have = k => fs.existsSync(path.join(ART, k + ".png")) || fs.existsSync(path.join(ART, k + ".jpg"));

const out = [];
const W = s => out.push(s);
const pct = f => Math.round(f * 100) + "%";

const parts = GM.ART.filter(a => a.kind === "part" && !have(a.key));
const byChar = {};
parts.forEach(a => (byChar[a.charId] = byChar[a.charId] || []).push(a));

