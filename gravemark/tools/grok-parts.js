/* ------------------------------------------------------------------ tiers */
function charBlock(charId, note) {
  const list = byChar[charId];
  if (!list || !list.length) return 0;
  const ref = list[0].ref;
  const refOk = ref && have(ref);
  W(`### \`${charId}\` — ${list.length} parts`);
  W("");
  W(`**Reference:** ${refOk ? "`art/" + ref + ".png` (exists — attach it)" : "`" + ref + "` — **not painted yet**: paint this character's idle first, then cut parts from it"}`);
  if (note) { W(""); W(note); }
  W("");
  W("| key | canvas | joint | at | paint only |");
  W("|---|---|---|---|---|");
  list.forEach(a => {
    W(`| \`${a.key}\` | ${a.w}×${a.h} | ${a.joint} | ${pct(a.pivot.x)} across, ${pct(a.pivot.y)} down | ${a.label.split(" — ").pop()} |`);
  });
  W("");
  return list.length;
}

function tier(n, title, why, ids, notes) {
  W("---");
  W("");
  W(`## Tier ${n}: ${title}`);
  W("");
  W(why);
  W("");
  let total = 0;
  ids.forEach(id => { total += charBlock(id, notes && notes[id]); });
  return total;
}

