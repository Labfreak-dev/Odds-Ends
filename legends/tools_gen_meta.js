// Card power for Ranked bots: run `node legends/tools_gen_meta.js [games]` after regenerating the cards (default 60,000 games, about a minute).
// Plays random bot decks against each other and records how often each card's side won when it was played.
const fs = require('fs');
const ROOT = require('path').resolve(__dirname);
const L = require(ROOT + '/js/engine.js');
const src = fs.readFileSync(ROOT + '/data/cards.js', 'utf8');
const data = JSON.parse(src.slice(src.indexOf('=') + 1, src.lastIndexOf(';')));
L.setData(data);
const CLS = ['tamer', 'gambler', 'healer', 'collector', 'scientist', 'champion'];
function seeded(s) { return () => { let t = (s += 0x6D2B79F5); t = Math.imul(t ^ (t >>> 15), t | 1); t ^= t + Math.imul(t ^ (t >>> 7), t | 61); return ((t ^ (t >>> 14)) >>> 0) / 4294967296; }; }
const rnd = seeded(12345);
const stat = {};
function play(d0, d1, c0, c1, seed, rec) {
  const G = L.newGame({ decks: [d0, d1], classes: [c0, c1], seed });
  G.p[0].isBot = G.p[1].isBot = true;
  L.botMulligan(G, 0); L.botMulligan(G, 1);
  const played = [new Set(), new Set()]; let t = 0;
  while (G.phase === 'play' && t++ < 200) { L.botTurn(G, G.turn); if (rec) G.ev.forEach(e => { if (e.t === 'play') played[e.pi].add(e.cid); }); G.ev.length = 0; }
  if (rec) [0, 1].forEach(pi => played[pi].forEach(cid => { const s = stat[cid] || (stat[cid] = [0, 0]); s[1]++; if (G.winner === pi) s[0]++; }));
  return G.winner;
}
const N = +process.argv[2] || 60000;
for (let k = 0; k < N; k++) { const a = CLS[k % 6], b = CLS[Math.floor(rnd() * 6)]; play(L.randomDeck(null, a, rnd), L.randomDeck(null, b, rnd), a, b, (rnd() * 1e9) | 0, true); }
// shrink toward .5 by sample size
const power = {};
Object.entries(stat).forEach(([id, [w, n]]) => { if (id === 'coin') return; power[id] = +((w + 10) / (n + 20)).toFixed(3); });
fs.writeFileSync(ROOT + '/data/meta.js', '/* GENERATED by legends/tools_gen_meta.js: how often each card\'s side won when it was played, from ' + N + ' random bot games (shrunk toward 50%). Ranked bots build stronger decks from it. */\nwindow.LL_META = ' + JSON.stringify({ games: N, power }) + ';\n');
console.log('cards', Object.keys(power).length);
